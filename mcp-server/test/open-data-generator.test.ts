import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { loadApprovedSnapshot } from '../src/lib/approved-snapshot.js';
import {
  generateTechnologyCandidate,
  loadOpenDataFixture,
  promoteCandidateAtomically,
  validateOpenDataSnapshot,
} from '../src/lib/open-data-generator.js';
import { technologyFixtureRows, technologyIdentityRegistry, technologyTaxonomy } from '../src/lib/open-data-fixture.js';

const commit = 'a'.repeat(40);
const generatedAt = '2026-09-14T22:00:00Z';
const snapshotId = 'technology-20260914-220000Z';

async function generate(outputDir: string, candidateSnapshotId = snapshotId) {
  return generateTechnologyCandidate({
    outputDir,
    rows: technologyFixtureRows,
    taxonomy: technologyTaxonomy,
    identityRegistry: technologyIdentityRegistry,
    generatedAt,
    snapshotId: candidateSnapshotId,
    pipelineCommit: commit,
    sourceName: 'fixture: technology-v1',
    workingTreeClean: true,
  });
}

test('loads a versioned fixture configuration without hard-coding source rows', async () => {
  const fixture = await loadOpenDataFixture(join(process.cwd(), 'test', 'fixtures', 'technology-open-data-v1.json'));
  assert.equal(fixture.taxonomy.version, '1.0.0');
  assert.equal(fixture.identityRegistry.version, '1.0.0');
  assert.equal(fixture.rows.length, 5);
});

test('generates every v2 artifact with a validating receipt', async () => {
  const root = await mkdtemp(join(tmpdir(), 'elicita-open-data-'));
  try {
    const candidate = join(root, 'candidate');
    const result = await generate(candidate);
    assert.deepEqual(result.artifacts.sort(), [
      'business-groups.csv', 'buyers.csv', 'checksums.sha256', 'companies.csv',
      'concentration.csv', 'coverage.csv', 'edges.csv', 'evolution.csv', 'exclusions.csv',
      'generation-receipt.json', 'methodology.json', 'snapshot.json',
    ]);
    await assert.doesNotReject(validateOpenDataSnapshot(candidate));
    await assert.doesNotReject(loadApprovedSnapshot({ approvedSnapshotDir: candidate }));
    const receipt = JSON.parse(await readFile(join(candidate, 'generation-receipt.json'), 'utf8'));
    assert.equal(receipt.snapshot_id, snapshotId);
    assert.equal(receipt.checks.rankings_deterministic, true);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test('identical fixture inputs generate bit-for-bit identical artifacts', async () => {
  const root = await mkdtemp(join(tmpdir(), 'elicita-open-data-'));
  try {
    const first = join(root, 'first');
    const second = join(root, 'second');
    await generate(first);
    await generate(second);
    const [firstChecksums, secondChecksums] = await Promise.all([
      readFile(join(first, 'checksums.sha256'), 'utf8'),
      readFile(join(second, 'checksums.sha256'), 'utf8'),
    ]);
    assert.equal(firstChecksums, secondChecksums);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test('input row order does not change the generated bytes', async () => {
  const root = await mkdtemp(join(tmpdir(), 'elicita-open-data-'));
  try {
    const first = join(root, 'first');
    const second = join(root, 'second');
    await generate(first);
    await generateTechnologyCandidate({
      outputDir: second,
      rows: [...technologyFixtureRows].reverse(),
      taxonomy: technologyTaxonomy,
      identityRegistry: technologyIdentityRegistry,
      generatedAt,
      snapshotId,
      pipelineCommit: commit,
      sourceName: 'fixture: technology-v1',
      workingTreeClean: true,
    });
    assert.equal(await readFile(join(first, 'checksums.sha256'), 'utf8'), await readFile(join(second, 'checksums.sha256'), 'utf8'));
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test('promotion replaces latest atomically only after validation', async () => {
  const root = await mkdtemp(join(tmpdir(), 'elicita-open-data-'));
  try {
    const candidate = join(root, 'candidate');
    const destination = join(root, 'published', 'technology');
    await generate(candidate);
    await promoteCandidateAtomically({ candidateDir: candidate, destinationRoot: destination });
    const replacement = join(root, 'replacement');
    const replacementId = 'technology-20260914-230000Z';
    await generate(replacement, replacementId);
    await promoteCandidateAtomically({ candidateDir: replacement, destinationRoot: destination });
    await assert.doesNotReject(validateOpenDataSnapshot(join(destination, 'latest'), { allowDirectorySymlink: true }));
    assert.equal(await readFile(join(destination, 'latest', 'snapshot.json'), 'utf8').then((text) => JSON.parse(text).snapshot_id), replacementId);
    await assert.doesNotReject(validateOpenDataSnapshot(join(destination, 'snapshots', snapshotId)));
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test('does not replace a valid latest snapshot when candidate validation fails', async () => {
  const root = await mkdtemp(join(tmpdir(), 'elicita-open-data-'));
  try {
    const destination = join(root, 'published', 'technology');
    const approved = join(root, 'approved');
    await generate(approved);
    await promoteCandidateAtomically({ candidateDir: approved, destinationRoot: destination });
    const invalid = join(root, 'invalid');
    await generate(invalid, 'technology-20260914-230000Z');
    const receiptPath = join(invalid, 'generation-receipt.json');
    const receipt = JSON.parse(await readFile(receiptPath, 'utf8'));
    receipt.outputs['companies.csv'] = `sha256:${'0'.repeat(64)}`;
    await import('node:fs/promises').then(({ writeFile }) => writeFile(receiptPath, `${JSON.stringify(receipt)}\n`, 'utf8'));
    await assert.rejects(promoteCandidateAtomically({ candidateDir: invalid, destinationRoot: destination }), /checksum/i);
    assert.equal(await readFile(join(destination, 'latest', 'snapshot.json'), 'utf8').then((text) => JSON.parse(text).snapshot_id), snapshotId);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test('rejects symlinked candidate artifacts', async () => {
  const root = await mkdtemp(join(tmpdir(), 'elicita-open-data-'));
  try {
    const candidate = join(root, 'candidate');
    await generate(candidate);
    const { symlink, unlink } = await import('node:fs/promises');
    await unlink(join(candidate, 'companies.csv'));
    await symlink(join(candidate, 'buyers.csv'), join(candidate, 'companies.csv'));
    await assert.rejects(validateOpenDataSnapshot(candidate), /regular file/);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

